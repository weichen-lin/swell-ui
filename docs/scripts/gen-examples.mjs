// Writes examples/index.ts from the files in examples/, so adding a demo never needs a manual registry edit.
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const dir = join(import.meta.dirname, '..', 'examples')
const out = join(dir, 'index.ts')

const names = (await readdir(dir))
  .filter((file) => file.endsWith('.tsx'))
  .map((file) => file.slice(0, -'.tsx'.length))
  .sort()

// `Example` suffix keeps identifiers clear of anything a demo might be named after
const ident = (name) => `${name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase())}Example`

const source = `// Generated by scripts/gen-examples.mjs. Do not edit; add a file to examples/ instead.
import type { ComponentType } from 'react'
${names.map((n) => `import ${ident(n)} from './${n}'`).join('\n')}

export const examples = {
${names.map((n) => `  '${n}': ${ident(n)},`).join('\n')}
} satisfies Record<string, ComponentType>

export type ExampleName = keyof typeof examples
`

const current = await readFile(out, 'utf8').catch(() => '')
// Skip identical writes so parallel runs and watchers don't churn
if (current !== source) await writeFile(out, source)
console.log(`gen-examples: ${names.length} examples`)
